AGENT = "A1"
PROMPT_ID = "p01_brief"
MODEL_MARKERS = ("deepseek", "gpt-", "claude", "gemini", "llama")


@dataclass(frozen=True)
class BriefOutcome:
    brief: BookBrief
    used_fallback: bool


def default_brief() -> BookBrief:
    return BookBrief(
        genre="literary fiction",
        subgenre="general",
        era_and_setting="unspecified",
        pov="unspecified",
        narrative_tense="past",
        narrative_distance="close",
        register="contemporary literary English",
        register_target_fa="literary-standard",
        address_policy="شما for strangers and elders, تو for intimates; otherwise follow the source",
        sentence_rhythm="preserve the source's sentence lengths, fragments and paragraph breaks",
        dialogue_style=(
            "contemporary Persian dialogue in «...» with the speaker and verb before the "
            "quotation (X گفت: «...»), never the English postposed tag; no regional slang"
        ),
        figurative_language="preserve images instead of explaining them",
        humor_irony="preserve dry understatement and irony without adding explanation",
        cultural_references_policy=(
            "keep cultural references; explain only when the plot requires it, "
            "at most one footnote per 2,000 words"
        ),
        name_policy="standard Persian transliteration with one fixed spelling per name",
        measurement_policy="keep source units; convert only when plot-relevant",
        foreign_text_policy="keep foreign phrases; footnote only when plot-critical",
        taboo_policy="translate faithfully; no softening and no added explicitness",
        footnote_policy="sparing",
        style_references=[],
        do_rules=[
            "جمله‌ها را به همان کوتاهی و بلندی متن اصلی نگه دار.",
            "تصویرها و استعاره‌ها را ترجمه کن، نه توضیح.",
            "نام‌ها را با یک صورت‌نویسی ثابت فارسی بنویس.",
            "گفت‌وگوها را با «...» و بدون افزودن توضیح بنویس؛ گوینده و فعل گفتن باید پیش از نقل قول بیاید («او گفت: ...»)، نه پس از آن.",
            "ابهام متن اصلی را حفظ کن.",
        ],
        dont_rules=[
            "از «می‌باشد» و ساختارهای اداری استفاده نکن.",
            "مترادف‌سازی تزئینی و افزودن صفت انجام نده.",
            "اصطلاحات و استعاره‌ها را در متن توضیح نده.",
            "لحن یا جمله‌های نویسنده را ساده و یکدست نکن.",
            "واژه‌های انگلیسی را بی‌دلیل در متن رها نکن.",
        ],
        key_motifs=[],
        uncertainties=["Brief generated by the conservative fallback; review when convenient."],
    )


def validate_brief(brief: BookBrief) -> None:
    rules = [*brief.do_rules, *brief.dont_rules]
    for rule in rules:
        if len(rule) > 200:
            raise SchemaValidationError("brief rule exceeds 200 characters")
        if any(marker in rule.lower() for marker in MODEL_MARKERS):
            raise SchemaValidationError("brief mentions a model name")


class BriefAnalyst:
    prompt_id = PROMPT_ID
    agent = AGENT

    def run(
        self,
        *,
        provider: Provider,
        tier: TierProfile,
        db: Database,
        run_id: str | None,
        cache: ResponseCache | None,
        book_title: str,
        book_author: str,
        sample_text: str,
        style_metrics: dict[str, Any],
        user_notes: str = "",
    ) -> BriefOutcome:
        prompt = load_prompt(self.prompt_id)
        variables = {
            "book_title": book_title or "Unknown",
            "book_author": book_author or "Unknown",
            "sample_text": sample_text,
            "style_metrics_json": json.dumps(
                style_metrics, sort_keys=True, ensure_ascii=False, indent=2
            ),
            "user_notes": user_notes,
        }
        try:
            result = run_agent(
                provider=provider,
                prompt=prompt,
                schema_model=BookBrief,
                variables=variables,
                tier=tier,
                db=db,
                run_id=run_id,
                cache=cache,
            )
            validate_brief(result.value)
            return BriefOutcome(brief=result.value, used_fallback=False)
        except SchemaValidationError as exc:
            db.upsert_issue(
                stage="analyze",
                code="A1_FALLBACK",
                dedupe_key="ch:book",
                severity="warn",
                message=f"brief validation failed; using the conservative default ({exc})",
            )
            return BriefOutcome(brief=default_brief(), used_fallback=True)


def brief_hash(brief: BookBrief) -> str:
    payload = json.dumps(
        brief.model_dump(), sort_keys=True, ensure_ascii=False, separators=(",", ":")
    )
    return f"sha256:{sha256_text(payload)}"


def brief_card(brief: BookBrief) -> str:
    """Compact stable card injected into P04/P05 (under ~500 tokens)."""
    lines = [
        f"genre: {brief.genre} / {brief.subgenre}",
        f"era and setting: {brief.era_and_setting}",
        f"pov: {brief.pov}",
        f"tense and distance: {brief.narrative_tense}; {brief.narrative_distance}",
        f"register: {brief.register}",
        f"target Persian: {brief.register_target_fa}",
        f"address policy: {brief.address_policy}",
        f"sentence rhythm: {brief.sentence_rhythm}",
        f"dialogue: {brief.dialogue_style}",
        f"figurative language: {brief.figurative_language}",
        f"humor and irony: {brief.humor_irony}",
        f"cultural references: {brief.cultural_references_policy}",
        f"names: {brief.name_policy}",
        f"measurements: {brief.measurement_policy}",
        f"foreign text: {brief.foreign_text_policy}",
        f"taboo: {brief.taboo_policy}",
        f"footnotes: {brief.footnote_policy}",
    ]
    if brief.style_references:
        lines.append("style references: " + " | ".join(brief.style_references))
    if brief.do_rules:
        lines.append("do rules:")
        lines.extend(f"- {rule}" for rule in brief.do_rules)
    if brief.dont_rules:
        lines.append("dont rules:")
        lines.extend(f"- {rule}" for rule in brief.dont_rules)
    if brief.key_motifs:
        lines.append("motifs:")
        lines.extend(f"- {motif.motif}: {motif.why_it_matters}" for motif in brief.key_motifs)
    return "\n".join(lines)


def _brief_payload(path: Path) -> dict[str, Any]:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise ConfigError(f"invalid brief YAML in {path}: {exc}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("brief"), dict):
        raise ConfigError(f"brief file {path} must contain a 'brief' mapping")
    return data


def _validated_brief(path: Path) -> BookBrief:
    try:
        return BookBrief.model_validate(_brief_payload(path)["brief"])
    except ValidationError as exc:
        raise ConfigError(f"brief file {path} does not validate:\n{exc}") from exc


def load_brief_draft(base: Path) -> BookBrief | None:
    path = base / "artifacts" / "brief.draft.yaml"
    if not path.is_file():
        return None
    return _validated_brief(path)


def load_approved_brief(base: Path) -> BookBrief | None:
    path = base / "artifacts" / "brief.yaml"
    if not path.is_file():
        return None
    return _validated_brief(path)


def write_brief_draft(base: Path, *, book_slug: str, brief: BookBrief) -> Path:
    path = base / "artifacts" / "brief.draft.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "version": 1,
        "book_slug": book_slug,
        "generated_at": utc_now_iso(),
        "brief": brief.model_dump(),
    }
    path.write_text(
        yaml.safe_dump(payload, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    return path


def freeze_brief(base: Path, *, book_slug: str, brief: BookBrief) -> tuple[Path, str]:
    path = base / "artifacts" / "brief.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    approved = utc_now_iso()
    digest = brief_hash(brief)
    payload = {
        "version": 1,
        "book_slug": book_slug,
        "approved": approved,
        "hash": digest,
        "brief": brief.model_dump(),
    }
    path.write_text(
        f"# approved: {approved}  hash: {digest}\n"
        + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    return path, digest
